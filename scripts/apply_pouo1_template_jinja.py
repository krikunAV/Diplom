def replace_in_para(para, old: str, new: str) -> bool:
    for run in para.runs:
        if old in run.text:
            run.text = run.text.replace(old, new, 1)
            return True
    full = "".join(r.text for r in para.runs)
    if old not in full:
        return False
    new_full = full.replace(old, new, 1)
    if para.runs:
        para.runs[0].text = new_full
        for r in para.runs[1:]:
            r.text = ""
    return True


def do_replacements(paragraphs, replacements: list[tuple[str, str]]) -> int:
    n = 0
    for para in paragraphs:
        for old, new in replacements:
            if old in para.text and replace_in_para(para, old, new):
                n += 1
    return n


