# app/pipeline/config.py
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class EngineConfig:
    """
    Глобальные параметры расчётного движка.
    Не зависит от конкретного сценария — только физические константы
    и настройки генерации артефактов.
    """

    # ── Атмосфера ─────────────────────────────────────────────────────────────
    p0_pa: float = 101_325.0    # атмосферное давление, Па
    c0_m_s: float = 330.0       # скорость звука, м/с

    # ── Методика расхода (натуральный газ) ────────────────────────────────────
    psi_critical: float = 0.7   # критическое давление
    mu_orifice: float = 0.8     # коэффициент расхода
    T_gas_K: float = 293.0      # температура газа, К
    R0_natgas: float = 486.0    # Дж/(кг·К)
    rho_natgas_n: float = 0.7   # плотность при н.у., кг/м³

    # ── Параметры облака ──────────────────────────────────────────────────────
    Z_cloud: float = 0.5        # коэффициент участия массы в облаке

    # ── ТВС-взрыв ─────────────────────────────────────────────────────────────
    tvs_range_id: int = 5       # класс пространства по методике 412
    tvs_sigma: float = 7.0      # относительная скорость горения
    tvs_max_r_m: float = 200.0  # максимальный радиус расчётной сетки, м

    # ── Энергетика ────────────────────────────────────────────────────────────
    beta_natgas: float = 1.14           # коэффициент участия энергии
    eud0_base_j_per_kg: float = 44e6   # удельная теплота сгорания, Дж/кг

    # ── Артефакты ─────────────────────────────────────────────────────────────
    make_charts: bool = True
    charts_output_dir: str = "out/charts"
