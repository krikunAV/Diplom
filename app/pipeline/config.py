# app/pipeline/config.py
from __future__ import annotations

from dataclasses import dataclass


@dataclass
class EngineConfig:
    """
    Глобальные параметры расчётного движка.
    Не зависит от конкретного сценария — только физические константы
    и настройки генерации артефактов.
    """

    # ── Атмосфера ─────────────────────────────────────────────────────────────
    p0_pa: float = 101_325.0    # атмосферное давление, Па
    c0_m_s: float = 330.0       # скорость звука, м/с

    # ── Методика расхода (натуральный газ) ────────────────────────────────────
    psi_critical: float = 0.7   # критическое давление
    mu_orifice: float = 0.8     # коэффициент расхода
    T_gas_K: float = 293.0      # температура газа, К
    R0_natgas: float = 486.0    # Дж/(кг·К)
    rho_natgas_n: float = 0.7   # плотность при н.у., кг/м³
    R0_lpg: float = 170.0       # Дж/(кг·К), пропан-бутановая смесь 60/40

    # ── Параметры облака ──────────────────────────────────────────────────────
    Z_cloud: float = 0.5        # коэффициент участия массы в облаке

    # ── ТВС-взрыв ─────────────────────────────────────────────────────────────
    tvs_range_id: int = 5       # класс пространства по методике 412
    tvs_sigma: float = 7.0      # относительная скорость горения
    tvs_max_r_m: float = 200.0  # максимальный радиус расчётной сетки, м

    # ── Энергетика ────────────────────────────────────────────────────────────
    beta_natgas: float = 1.14           # коэффициент участия энергии
    eud0_base_j_per_kg: float = 44e6   # удельная теплота сгорания, Дж/кг

    # ── Резервуарный парк (общее) ─────────────────────────────────────────────
    # Коэффициент участия массы в облаке ТВС (открытая площадка, жидкое горючее)
    # Источник: РД 03-409-01, Табл.1
    Z_tank: float = 0.1

    # ── Резервуарный парк — дизельное топливо ─────────────────────────────────
    # Значения синхронизированы с docs/methodology/METHODOLOGY_POUO1_DT.md.
    # ENGINEER_CHECK: rho=860 кг/м³ выше типового диапазона ГОСТ 305 для ДТ-Л,
    # но оставлено как в templatePOUO1_DT.docx / методологии.
    diesel_rho_liq_kg_m3: float = 860.0
    diesel_eud0_j_per_kg: float = 43.59e6
    diesel_calc_temp_c: float = 36.0
    diesel_antoine_A: float = 5.07818
    diesel_antoine_B: float = 1255.73
    diesel_antoine_C: float = 199.523
    diesel_lower_flammability_pct: float = 0.6
    diesel_formula_nC: float = 12.343
    diesel_formula_nH: float = 26.889
    diesel_formula_nX: float = 0.0
    diesel_formula_nO: float = 0.0
    diesel_air_density_kg_m3: float = 1.1455
    # РД 03-409-01: для сильно загромождённого пространства шаблон принимает
    # верхнюю границу диапазона 4 (150-200 м/с).
    diesel_tvs_range_id: int = 4
    diesel_tvs_vg_m_s: float = 200.0
    # Давление насыщенных паров при расчётной (летней) температуре 36°C, кПа.
    # Рассчитано по уравнению Антуана: PS = 10^(5.07818 - 1255.73/(199.523+36)) ≈ 0.558 кПа
    # Источник РПЗ: PS = 0.558 кПа при t = 36°C (максимальная по региону).
    # Формула ГОСТ Р 12.3.047-2012, Прил.К: W = 10⁻⁶ × η × Pнас(кПа) × √M
    # ⚠ Уточнить по расчётной температуре конкретного объекта.
    diesel_Pnas_kpa: float = 0.558
    # Средняя молярная масса дизельного топлива C₁₂H₂₆ (по РПЗ: M = 172.3 г/моль)
    # Для C₁₂–C₁₄: диапазон 170–200; принимается 172.3 как в источнике.
    diesel_M_g_mol: float = 172.3
    # Среднеповерхностная интенсивность излучения пожара пролива дизеля, кВт/м²
    # Источник: ГОСТ Р 12.3.047-2012, Табл. Б.1
    diesel_Ef_pool_kw_m2: float = 25.0
    # Среднеповерхностная интенсивность излучения огненного шара дизеля, кВт/м².
    # ENGINEER_CHECK: ГОСТ Р 12.3.047-2012, Табл. Б.1 может давать 47 кВт/м²;
    # методология POUO1_DT фиксирует 25 кВт/м² как значение шаблона.
    diesel_Ef_fireball_kw_m2: float = 25.0
    # Удельная скорость выгорания дизеля, кг/(м²·с)
    # Источник: ГОСТ Р 12.3.047-2012, Прил.П (справочные данные)
    diesel_burn_rate_kg_m2_s: float = 0.040
    # Коэффициент расширения продуктов сгорания (для дефлаграции ТВС)
    # Источник: ГОСТ Р 12.3.047-2012, Табл. Д.1
    sigma_diesel: float = 6.5

    # ── Резервуарный парк — СУГ (пропан-бутан) ───────────────────────────────
    # Доля мгновенного вскипания при разгерметизации резервуара
    # Упрощённое значение; точный расчёт: Cp * ΔT / L_vap ≈ 0.38
    lpg_flash_fraction: float = 0.30
    # Доля испарения остатка из пролива (консервативная оценка)
    lpg_pool_evap_fraction: float = 0.10
    # Среднеповерхностная интенсивность излучения факела СУГ, кВт/м²
    # Источник: ГОСТ Р 12.3.047-2012, Табл. Б.1 (пропан)
    lpg_Ef_jet_kw_m2: float = 130.0
    # Среднеповерхностная интенсивность излучения огненного шара СУГ (BLEVE), кВт/м²
    # Источник: TNO Green Book (CPR 14E), гл. 6 (огненный шар пропана)
    lpg_Ef_fireball_kw_m2: float = 150.0
    # Коэффициент расширения продуктов сгорания СУГ
    sigma_lpg: float = 7.0

    # ── Артефакты ─────────────────────────────────────────────────────────────
    make_charts: bool = True
    charts_output_dir: str = "out/charts"
